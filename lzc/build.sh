#!/bin/sh
# Generates lzc/gen/Dockerfile for the packaged Paseo image: the official
# upstream image for the version in package.yml (the same image upstream
# documents for Docker), with the agent CLIs the base image deliberately
# leaves out (docs/docker.md) added on top.
#
# Run by lzc-build.yml's `buildscript` before the image build; run it by hand
# to inspect or build the image yourself:
#   sh lzc/build.sh && docker build -f lzc/gen/Dockerfile lzc/gen
#
# Two deliberate choices:
#  - The npm registry is the China mirror (registry.npmmirror.com). The Lazycat
#    boxes and typical dev machines cannot rely on registry.npmjs.org. Set
#    NPM_REGISTRY to override, e.g. NPM_REGISTRY=https://registry.npmjs.org.
#  - Agent versions are pinned in lzc/agents.env; a floating install would make
#    the same lpk build differently on different days.
set -e
cd "$(dirname "$0")/.."

version=$(sed -n 's/^version:[[:space:]]*//p' package.yml | head -1 | tr -d ' "'"'"'')
[ -n "$version" ] || { echo "lzc/build.sh: cannot read version from package.yml" >&2; exit 1; }

# The upstream image tag is the upstream release, without any local build
# suffix we add for lpk-only rebuilds (0.12.0+lzc1 -> 0.12.0).
image_version=${version%%+*}
[ -n "$image_version" ] || { echo "lzc/build.sh: version '$version' has no image tag" >&2; exit 1; }

# shellcheck disable=SC1091
. ./lzc/agents.env
for name in CLAUDE_CODE_VERSION CODEX_VERSION OPENCODE_VERSION COPILOT_VERSION; do
  eval "value=\$$name"
  [ -n "$value" ] || { echo "lzc/build.sh: $name is not set in lzc/agents.env" >&2; exit 1; }
done

npm_registry=${NPM_REGISTRY:-https://registry.npmmirror.com}

mkdir -p lzc/gen
cat > lzc/gen/Dockerfile <<EOF
# Generated by lzc/build.sh - do not edit; edit lzc/agents.env instead.
FROM ghcr.io/getpaseo/paseo:${image_version}

USER root
# The global npm registry also serves the agents' own npx installs at runtime.
RUN npm config set --location=global registry ${npm_registry} \\
 && npm install -g --no-fund --no-audit \\
      @anthropic-ai/claude-code@${CLAUDE_CODE_VERSION} \\
      @openai/codex@${CODEX_VERSION} \\
      opencode-ai@${OPENCODE_VERSION} \\
      @github/copilot@${COPILOT_VERSION} \\
 && npm cache clean --force

# Smoke every agent Paseo knows how to spawn; a base image bump that renames an
# executable should fail the build, not the user's first session.
RUN claude --version && codex --version && opencode --version && copilot --version
EOF

# Fail loudly if generation drifted from package.yml instead of shipping a
# stale image tag.
grep -q "^FROM ghcr.io/getpaseo/paseo:${image_version}$" lzc/gen/Dockerfile
echo "lzc/build.sh: wrote lzc/gen/Dockerfile (paseo ${version}, image tag ${image_version}, registry ${npm_registry})"
